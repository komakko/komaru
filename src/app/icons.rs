#[derive(Clone, Copy)]
pub enum Icon {
    Close,
    Minimize,
    Maximize,
    Restore,
    Pin { pinned: bool },
    Resize,
    Crop,
    Rotate,
    Flip,
    ColorPicker,
    Pixels,
    Link,
    Reset,
    Copy,
    Info,
    Play,
    Pause,
    StepBack,
    StepForward,
    Opacity,
}

pub fn paint(painter: &Painter, center: Pos2, reach: f32, icon: Icon, color: Color32) {
    let sketch = Sketch {
        painter,
        center,
        reach,
        color,
        stroke: Stroke::new(STROKE_WIDTH, color),
    };
    match icon {
        Icon::Close => {
            sketch.line(&[(-1.0, -1.0), (1.0, 1.0)]);
            sketch.line(&[(-1.0, 1.0), (1.0, -1.0)]);
        }
        Icon::Minimize => sketch
            .widened(HEAVY_STROKE_WIDTH)
            .line(&[(-1.0, 0.78), (1.0, 0.78)]),
        Icon::Maximize => sketch.rect((-1.0, -1.0), (1.0, 1.0)),
        Icon::Restore => {
            sketch.rect((-1.0, -0.45), (0.45, 1.0));
            sketch.line(&[
                (-0.45, -0.45),
                (-0.45, -1.0),
                (1.0, -1.0),
                (1.0, 0.45),
                (0.45, 0.45),
            ]);
        }
        Icon::Pin { pinned } => {
            let share = if pinned {
                PINNED_STROKE_SHARE
            } else {
                GLYPH_STROKE_SHARE
            };
            sketch.glyphs(PIN, share);
        }
        Icon::Resize => sketch.glyphs(RESIZE, GLYPH_STROKE_SHARE),
        Icon::Crop => sketch.glyphs(CROP, GLYPH_STROKE_SHARE),
        Icon::Rotate => sketch.glyphs(ROTATE, GLYPH_STROKE_SHARE),
        Icon::Reset => sketch.glyphs(RESET, GLYPH_STROKE_SHARE),
        Icon::Link => sketch.glyphs(LINK, GLYPH_STROKE_SHARE),
        Icon::Copy => sketch.glyphs(COPY, GLYPH_STROKE_SHARE),
        Icon::Flip => sketch.glyphs(FLIP, GLYPH_STROKE_SHARE),
        Icon::ColorPicker => sketch.glyphs(PIPETTE, GLYPH_STROKE_SHARE),
        Icon::Opacity => sketch.glyphs(OPACITY, GLYPH_STROKE_SHARE),
        Icon::Info => {
            sketch.circle((0.0, 0.0), 1.0, false);
            sketch.circle((0.0, -0.5), 0.11, true);
            sketch.line(&[(0.0, -0.1), (0.0, 0.55)]);
        }
        Icon::Play => sketch.polygon(&[(-0.6, -1.0), (-0.6, 1.0), (0.95, 0.0)]),
        Icon::Pause => {
            sketch.block((-0.75, -1.0), (-0.2, 1.0));
            sketch.block((0.2, -1.0), (0.75, 1.0));
        }
        Icon::StepBack => {
            sketch.block((-1.0, -0.9), (-0.7, 0.9));
            sketch.polygon(&[(0.95, -0.9), (0.95, 0.9), (-0.5, 0.0)]);
        }
        Icon::StepForward => {
            sketch.block((0.7, -0.9), (1.0, 0.9));
            sketch.polygon(&[(-0.95, -0.9), (-0.95, 0.9), (0.5, 0.0)]);
        }
        Icon::Pixels => {
            sketch.rect((-1.0, -1.0), (1.0, 1.0));
            sketch.block((-1.0, -1.0), (0.0, 0.0));
            sketch.block((0.0, 0.0), (1.0, 1.0));
        }
    }
}

#[derive(Clone, Copy)]
struct Sketch<'a> {
    painter: &'a Painter,
    center: Pos2,
    reach: f32,
    color: Color32,
    stroke: Stroke,
}

impl Sketch<'_> {
    fn widened(self, width: f32) -> Self {
        Self {
            stroke: Stroke::new(width, self.color),
            ..self
        }
    }

    fn point(&self, (x, y): Unit) -> Pos2 {
        self.center + Vec2::new(x, y) * self.reach
    }

    fn span(&self, min: Unit, max: Unit) -> Rect {
        Rect::from_min_max(self.point(min), self.point(max))
    }

    fn line(&self, points: &[Unit]) {
        let points = points.iter().map(|&unit| self.point(unit)).collect();
        self.painter.add(Shape::line(points, self.stroke));
    }

    fn rect(&self, min: Unit, max: Unit) {
        self.painter
            .rect_stroke(self.span(min, max), 0.0, self.stroke, StrokeKind::Middle);
    }

    fn block(&self, min: Unit, max: Unit) {
        self.painter
            .rect_filled(self.span(min, max), 0.0, self.color);
    }

    fn circle(&self, center: Unit, radius: f32, filled: bool) {
        let center = self.point(center);
        let radius = radius * self.reach;
        if filled {
            self.painter.circle_filled(center, radius, self.color);
        } else {
            self.painter.circle_stroke(center, radius, self.stroke);
        }
    }

    fn polygon(&self, points: &[Unit]) {
        let points = points.iter().map(|&unit| self.point(unit)).collect();
        self.painter
            .add(Shape::convex_polygon(points, self.color, Stroke::NONE));
    }

    fn glyphs(&self, glyphs: &[Glyph], share: f32) {
        let width = (self.reach * share).max(MIN_GLYPH_STROKE);
        let pen = self.widened(width);
        for glyph in glyphs {
            match glyph {
                Glyph::Open(points) => pen.open(points),
                Glyph::Closed(points) => pen.closed(points),
                Glyph::Circle(center, radius) => pen.circle(*center, *radius, false),
            }
        }
    }

    fn open(&self, points: &[Unit]) {
        self.line(points);
        for end in [points.first(), points.last()].into_iter().flatten() {
            self.painter
                .circle_filled(self.point(*end), self.stroke.width / 2.0, self.color);
        }
    }

    fn closed(&self, points: &[Unit]) {
        let points = points.iter().map(|&unit| self.point(unit)).collect();
        self.painter.add(Shape::closed_line(points, self.stroke));
    }
}
